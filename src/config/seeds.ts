import { createHash } from 'crypto';
import { existsSync, readFileSync } from 'fs';
import { join } from 'path';
import yaml from 'js-yaml';
import { z } from 'zod';

interface SeedSourceEntry {
  type: string;
  identifier: string;
}

function seedKey(type: string, identifier: string): string {
  return `${type.toLowerCase()}::${identifier.toLowerCase()}`;
}

/**
 * Whether (type, identifier) is one of the maintained default seed-list
 * entries in src/config/seed-sources.yml. `runner/scan.ts`'s seedSources()
 * re-inserts every entry here (INSERT OR IGNORE) on each scan, so a route
 * that lets the user hard-delete one of these would just have it reappear —
 * callers should soft-disable instead. Comparison is case-insensitive.
 */
export function isSeededSource(type: string, identifier: string): boolean {
  const seedPath = join(process.cwd(), 'src/config/seed-sources.yml');
  const raw = yaml.load(readFileSync(seedPath, 'utf-8')) as { sources?: SeedSourceEntry[] };
  return (raw.sources ?? []).some(s => seedKey(s.type, s.identifier) === seedKey(type, identifier));
}

/** Per-company board types the discovery script can find (Workday and BambooHR
 *  need more than a slug, so they are never discovered). */
export const DISCOVERABLE_TYPES = [
  'greenhouse', 'ashby', 'lever', 'workable', 'smartrecruiters',
  'recruitee', 'personio', 'breezy', 'teamtailor', 'rippling',
] as const;

export type DiscoverableType = (typeof DISCOVERABLE_TYPES)[number];

const DiscoveredEntrySchema = z.object({
  type: z.enum(DISCOVERABLE_TYPES),
  identifier: z.string().refine(s => /^[a-z0-9][a-z0-9.\-]{0,63}$/i.test(s) && !s.includes('..')),
  display_name: z.string().min(1).max(200),
});

export type DiscoveredSource = z.infer<typeof DiscoveredEntrySchema>;

export const DISCOVERED_SOURCES_FILE = 'src/config/discovered-sources.json';

/** Content hash of discovered-sources.json, or null when the file is absent. */
export function discoveredSourcesFingerprint(): string | null {
  const path = join(process.cwd(), DISCOVERED_SOURCES_FILE);
  if (!existsSync(path)) return null;
  return createHash('sha1').update(readFileSync(path)).digest('hex');
}

/**
 * Boards verified live by scripts/discover-boards.ts, read from the generated
 * src/config/discovered-sources.json. Absent file means none (a fresh checkout
 * before the script has ever run). Entries failing validation are skipped and
 * counted in a warning rather than failing the scan, since the file feeds URL
 * construction and is regenerated by tooling.
 */
export function loadDiscoveredSources(): DiscoveredSource[] {
  const path = join(process.cwd(), DISCOVERED_SOURCES_FILE);
  if (!existsSync(path)) return [];
  const raw = JSON.parse(readFileSync(path, 'utf-8')) as { sources?: unknown[] };
  const entries = Array.isArray(raw.sources) ? raw.sources : [];
  const valid: DiscoveredSource[] = [];
  for (const entry of entries) {
    const parsed = DiscoveredEntrySchema.safeParse(entry);
    if (parsed.success) valid.push(parsed.data);
  }
  if (valid.length < entries.length) {
    console.warn(`[seeds] skipped ${entries.length - valid.length} invalid entries in ${DISCOVERED_SOURCES_FILE}`);
  }
  return valid;
}
